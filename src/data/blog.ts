// Helper: get articles by page
export function getArticlesByPage(page: number): IBlogArticle[] {
  const start = (page - 1) * POSTS_PER_PAGE;
  return articles.slice(start, start + POSTS_PER_PAGE);
}

// Helper: total pages
export function getTotalPages(): number {
  return Math.ceil(articles.length / POSTS_PER_PAGE);
}

// Helper: get article by slug
